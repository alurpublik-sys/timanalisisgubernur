create table if not exists public.finalisasi_honor (
  id bigint generated by default as identity primary key,
  kode text generated always as ('FINROW-' || lpad(id::text, 6, '0')) stored unique,
  finalization_id text not null,
  periode char(7) not null check (periode ~ '^\d{4}-\d{2}$'),
  finalized_at timestamptz not null default now(),
  status text not null default 'FINAL',
  tim_id bigint references public.tim_analisis(id) on delete restrict,
  nama_anggota text not null,
  peran text,
  required_agenda integer not null default 0,
  hadir integer not null default 0,
  izin integer not null default 0,
  tidak_hadir integer not null default 0,
  kehadiran_wajib_pct numeric(7,2) not null default 0,
  opd_excluded boolean not null default false,
  opd_required integer not null default 0,
  opd_hadir integer not null default 0,
  opd_pct numeric(7,2) not null default 0,
  rapat_required integer not null default 0,
  rapat_hadir integer not null default 0,
  rapat_pct numeric(7,2) not null default 0,
  total_kontribusi integer not null default 0,
  output_selesai integer not null default 0,
  poin_kontribusi numeric(12,2) not null default 0,
  basis_evaluasi text,
  nilai_evaluasi_pct numeric(7,2) not null default 0,
  rekomendasi_potongan numeric(14,2) not null default 0,
  honor_direkomendasikan numeric(14,2) not null default 0,
  label_rekomendasi text,
  catatan text,
  reopened_at timestamptz,
  reopened_reason text,
  unique (finalization_id, tim_id)
);

