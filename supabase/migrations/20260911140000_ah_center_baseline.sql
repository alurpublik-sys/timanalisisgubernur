create or replace function private.is_active_member()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.profiles p where p.user_id = auth.uid() and p.active = true);
$$;
create or replace function private.has_role(allowed_roles text[])
returns boolean language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.profiles p where p.user_id = auth.uid() and p.active = true and p.role = any(allowed_roles));
$$;
revoke all on function private.is_active_member() from public, anon;
revoke all on function private.has_role(text[]) from public, anon;
grant execute on function private.is_active_member() to authenticated;
grant execute on function private.has_role(text[]) to authenticated;

